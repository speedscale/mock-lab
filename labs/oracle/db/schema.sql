-- Called as an anonymous PL/SQL block, so the recording holds a procedure call
-- with an OUT parameter and a REF CURSOR OUT bind next to the plain statements.
-- A REF CURSOR rather than an implicit result, because go-ora cannot read
-- implicit results.
CREATE PROCEDURE top_products (
    p_limit IN  NUMBER,
    p_total OUT NUMBER,
    p_top   OUT SYS_REFCURSOR
) AS
BEGIN
    OPEN p_top FOR
        SELECT p.id, p.name, SUM(o.quantity) AS sold
        FROM orders o JOIN products p ON p.id = o.product_id
        GROUP BY p.id, p.name
        ORDER BY sold DESC, p.id
        FETCH FIRST p_limit ROWS ONLY;
    SELECT COUNT(*) INTO p_total FROM orders;
END;
/
EXIT
