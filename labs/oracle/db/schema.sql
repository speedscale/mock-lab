-- The lab's shop schema: products, orders, and a stored procedure for the
-- report. The image creates the user "shop" in FREEPDB1 from APP_USER, and the
-- app signs in as it, so these objects live in its schema. Running this again
-- resets the data, so every recording starts from the same rows.
WHENEVER SQLERROR EXIT FAILURE
SET FEEDBACK OFF
DROP PROCEDURE IF EXISTS top_products;
DROP TABLE IF EXISTS orders PURGE;
DROP TABLE IF EXISTS products PURGE;

CREATE TABLE products (
    id          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku         VARCHAR2(20)      NOT NULL CONSTRAINT uq_products_sku UNIQUE,
    name        VARCHAR2(100 CHAR) NOT NULL,
    category    VARCHAR2(20)      NOT NULL,
    price_cents NUMBER(10)        NOT NULL,
    stock       NUMBER(10)        NOT NULL CONSTRAINT ck_products_stock CHECK (stock >= 0)
);
CREATE TABLE orders (
    id          NUMBER(10) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    product_id  NUMBER(10) NOT NULL REFERENCES products (id),
    quantity    NUMBER(10) NOT NULL CHECK (quantity > 0),
    total_cents NUMBER(10) NOT NULL
);

